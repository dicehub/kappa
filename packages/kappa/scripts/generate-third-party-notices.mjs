import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { adaptedSources } from "./third-party-sources.mjs";

const packageRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const distRoot = resolve(packageRoot, "dist");
const manifest = JSON.parse(readFileSync(resolve(packageRoot, "package.json"), "utf8"));

const walk = (directory) =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });

const bundledPackageName = (source) => {
  const normalized = source.replaceAll("\\", "/");
  const marker = "/node_modules/";
  const markerIndex = normalized.lastIndexOf(marker);
  if (markerIndex === -1) return null;

  const parts = normalized.slice(markerIndex + marker.length).split("/");
  return parts[0]?.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0] || null;
};

const bundledPackages = new Set();
for (const mapPath of walk(distRoot).filter((path) => path.endsWith(".map"))) {
  const sourceMap = JSON.parse(readFileSync(mapPath, "utf8"));
  for (const source of sourceMap.sources ?? []) {
    const packageName = bundledPackageName(source);
    if (packageName) bundledPackages.add(packageName);
  }
}

if (bundledPackages.size > 0) {
  throw new Error(
    `Third-party source is bundled in dist: ${[...bundledPackages].sort().join(", ")}. ` +
      "Externalize it or add its full license notice before publishing.",
  );
}

const dependencyGroups = [
  ["Runtime dependency", manifest.dependencies ?? {}],
  ["Peer dependency", manifest.peerDependencies ?? {}],
];

const rows = dependencyGroups.flatMap(([role, dependencies]) =>
  Object.entries(dependencies).map(([name, range]) => {
    const dependencyManifestPath = resolve(packageRoot, "node_modules", name, "package.json");
    if (!existsSync(dependencyManifestPath)) {
      throw new Error(`Cannot read the installed manifest for ${name}. Run \`pnpm install\`.`);
    }

    const dependencyManifest = JSON.parse(readFileSync(dependencyManifestPath, "utf8"));
    const license = dependencyManifest.license ?? "See package";
    const dependencyRole = role === "Peer dependency" && manifest.peerDependenciesMeta?.[name]?.optional
      ? "Optional peer"
      : role;
    return { license, name, range, role: dependencyRole };
  }),
);

const output = [
  "# Third-party notices",
  "",
  "Generated by `pnpm --filter @dicehub/kappa codegen:licenses`.",
  "",
  "Kappa includes adapted third-party source covered by the full notices below. Runtime dependencies and peers are installed separately by consumers and keep their own license terms.",
  "",
  "| Package | Required range | Role | License |",
  "| --- | --- | --- | --- |",
  ...rows
    .sort((left, right) => left.name.localeCompare(right.name))
    .map(({ license, name, range, role }) => `| \`${name}\` | \`${range}\` | ${role} | ${license} |`),
  "",
  "## Adapted source",
  "",
  ...adaptedSources.flatMap(({ name, repository, reference, licenseFile, scope }) => [
    `### ${name}`,
    "",
    `Source: [${name}](${repository}). ${scope}`,
    "",
    `Reviewed reference: [\`${reference}\`](${repository}/tree/${reference}). This identifies the inspected reference, not the original revision of every adaptation.`,
    "",
    readFileSync(resolve(packageRoot, licenseFile), "utf8").trim(),
    "",
  ]),
  "## Ark UI Vue",
  "",
  `External runtime dependency: \`@ark-ui/vue\` ${manifest.dependencies["@ark-ui/vue"]}. The notice below is copied from that installed package.`,
  "",
  readFileSync(resolve(packageRoot, "node_modules/@ark-ui/vue/LICENSE"), "utf8").trim(),
  "",
].join("\n");

const outputPath = resolve(packageRoot, "THIRD_PARTY_NOTICES.md");
writeFileSync(outputPath, output);
console.log(`Generated ${relative(packageRoot, outputPath)} for ${rows.length} packages.`);
